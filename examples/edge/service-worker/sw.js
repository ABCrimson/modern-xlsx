/**
 * Service Worker — Generate XLSX files in a Service Worker context.
 *
 * This example intercepts fetch requests and generates XLSX files
 * entirely inside the Service Worker, without touching the main thread.
 *
 * Register from your page as a classic worker (no `type: 'module'`):
 *   navigator.serviceWorker.register('/sw.js');
 *
 * The worker is classic because it loads the IIFE bundle with importScripts().
 * The ES module build imports the `#runtime` specifier from the package's
 * `imports` map, which only Node or a bundler resolves; a service worker has
 * no import map, so the module build cannot load from a CDN. The IIFE bundle
 * already contains the browser runtime and defines the `ModernXlsx` global.
 */

const base = 'https://cdn.jsdelivr.net/npm/modern-xlsx@1.3.0/dist/';

importScripts(`${base}modern-xlsx.min.js`);

function ensureInit() {
  // A worker has no document, so the IIFE cannot find its .wasm on its own: pass the URL.
  // initWasm shares one in-flight load and retries after a failure.
  return ModernXlsx.initWasm(`${base}modern-xlsx.wasm`);
}

self.addEventListener('install', (event) => {
  // Pre-initialize WASM during install
  event.waitUntil(ensureInit());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Intercept requests to /api/xlsx/generate
  if (url.pathname === '/api/xlsx/generate') {
    event.respondWith(handleGenerate());
    return;
  }
});

async function handleGenerate() {
  try {
    await ensureInit();

    const wb = new ModernXlsx.Workbook();
    const ws = wb.addSheet('SW Generated');
    ws.cell('A1').value = 'Generated by Service Worker';
    ws.cell('B1').value = new Date().toISOString();

    return new Response(await wb.toBuffer(), {
      headers: {
        'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'Content-Disposition': 'attachment; filename="sw-generated.xlsx"',
      },
    });
  } catch {
    return new Response('XLSX generation failed', {
      status: 500,
      headers: { 'Content-Type': 'text/plain' },
    });
  }
}
