#!/usr/bin/env node
// Smoke test for examples/edge/service-worker/sw.js. It serves the example worker and the built
// dist/ files from a local server (the CDN URLs are rewritten to /cdn/), registers the worker
// in Chromium, fetches /api/xlsx/generate through it, and reads the returned bytes back with
// the package's Node build. Run it after `pnpm build`:
//
//   node scripts/sw-smoke.mjs
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';

const pkg = join(import.meta.dirname, '..');
const dist = join(pkg, 'dist');
const swPath = join(pkg, '..', '..', 'examples', 'edge', 'service-worker', 'sw.js');
const XLSX_MIME = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
const CDN_PREFIX = /https:\/\/cdn\.jsdelivr\.net\/npm\/modern-xlsx@[^/'"`\s]+\//g;
const DIST_TYPES = {
  '.js': 'text/javascript',
  '.mjs': 'text/javascript',
  '.wasm': 'application/wasm',
};

// A page that registers /sw.js and settles once the worker controls it. clients.claim() can
// race the first fetch, so it waits for controllerchange instead of a timer.
const PAGE = `<!doctype html><meta charset="utf-8"><title>sw smoke</title>
<script>
  globalThis.swControlled = (async () => {
    await navigator.serviceWorker.register('/sw.js');
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) {
      await new Promise((resolve) =>
        navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }),
      );
    }
  })();
</script>`;

function send(res, status, type, body) {
  res.writeHead(status, { 'Content-Type': type });
  res.end(body);
}

function serveDist(res, pathname) {
  const name = pathname.slice('/cdn/dist/'.length);
  const ext = name.slice(name.lastIndexOf('.'));
  const file = join(dist, name);
  if (name.includes('/') || name.includes('\\') || !(ext in DIST_TYPES) || !existsSync(file)) {
    send(res, 404, 'text/plain', 'not found');
    return;
  }
  send(res, 200, DIST_TYPES[ext], readFileSync(file));
}

function handle(req, res) {
  const { pathname } = new URL(req.url ?? '/', 'http://localhost');
  if (req.method !== 'GET') send(res, 405, 'text/plain', 'method not allowed');
  else if (pathname === '/') send(res, 200, 'text/html', PAGE);
  else if (pathname === '/sw.js') {
    const source = readFileSync(swPath, 'utf8').replace(CDN_PREFIX, '/cdn/');
    send(res, 200, 'text/javascript', source);
  } else if (pathname.startsWith('/cdn/dist/')) serveDist(res, pathname);
  else send(res, 404, 'text/plain', 'not found');
}

function listen() {
  const server = createServer(handle);
  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => resolve(server));
  });
}

async function generateViaWorker(browser, origin) {
  const page = await browser.newPage();
  page.on('pageerror', (err) => console.error(`page error: ${err.message}`));
  await page.goto(`${origin}/`);
  await page.evaluate(() => globalThis.swControlled);
  const result = await page.evaluate(async () => {
    const res = await fetch('/api/xlsx/generate');
    return {
      status: res.status,
      contentType: res.headers.get('content-type'),
      bytes: [...new Uint8Array(await res.arrayBuffer())],
    };
  });
  return { ...result, bytes: Uint8Array.from(result.bytes) };
}

async function verify({ status, contentType, bytes }) {
  assert.equal(status, 200, 'worker response status');
  assert.equal(contentType, XLSX_MIME, 'worker response content-type');
  const { initWasm, readBuffer } = await import(pathToFileURL(join(dist, 'index.mjs')).href);
  await initWasm();
  const wb = await readBuffer(bytes);
  assert.deepEqual(wb.sheetNames, ['SW Generated'], 'sheet names');
  assert.equal(wb.getSheet('SW Generated').cell('A1').value, 'Generated by Service Worker', 'A1');
}

async function main() {
  for (const file of ['modern-xlsx.min.js', 'modern-xlsx.wasm']) {
    if (!existsSync(join(dist, file)))
      throw new Error(`dist/${file} is missing: build the package first`);
  }
  const server = await listen();
  let browser;
  try {
    const origin = `http://localhost:${server.address().port}`;
    browser = await chromium.launch();
    await verify(await generateViaWorker(browser, origin));
    console.log('sw-smoke: OK');
  } finally {
    await browser?.close();
    server.close();
  }
}

main().catch((err) => {
  console.error(`sw-smoke: FAILED: ${err instanceof Error ? err.message.split('\n')[0] : err}`);
  process.exit(1);
});
